CREATE TABLE job_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    job_id        VARCHAR(255) NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    started_at    TIMESTAMPTZ  NOT NULL,
    finished_at   TIMESTAMPTZ,
    attempts      INTEGER      NOT NULL DEFAULT 0,
    error_message VARCHAR(2000),
    CONSTRAINT pk_job_run          PRIMARY KEY (id),
    CONSTRAINT ck_job_run_attempts CHECK (attempts >= 0)
);

-- Serves lastRun(jobId) and, as a prefix, any lookup by job_id
CREATE INDEX idx_job_run_job_id_started_at ON job_run (job_id, started_at);
